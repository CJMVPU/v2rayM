import Foundation

private struct WireContract: Decodable {
    let protocolVersion: Int
    let actions: [String]
    let resourceExtensions: [String]
    let limits: [String: Int]
}

func generateHelperContract(root: URL, checkOnly: Bool) throws {
    let data = try Data(contentsOf: root.appendingPathComponent("contracts/tun-helper/contract.json"))
    let spec = try JSONDecoder().decode(WireContract.self, from: data)
    let path = root.appendingPathComponent("macos/TunHelper/Sources/TunShared/HelperContract.generated.swift")
    func setLiteral(_ values: [String]) -> String {
        "[" + values.map { String(reflecting: $0) }.joined(separator: ", ") + "]"
    }
    var lines = [
        "// Generated by scripts/project-tool generate-helper-contract. Do not edit.",
        "public enum HelperContract {",
        "    public static let version = \(spec.protocolVersion)",
        "    public static let actions: Set<String> = \(setLiteral(spec.actions))",
        "    public static let resourceExtensions: Set<String> = \(setLiteral(spec.resourceExtensions))",
    ]
    for (name, limit) in spec.limits.sorted(by: { $0.key < $1.key }) {
        lines.append("    public static let \(name) = \(limit)")
    }
    let output = Data((lines + ["}", ""]).joined(separator: "\n").utf8)
    if checkOnly {
        guard try Data(contentsOf: path) == output else { throw ToolFailure("Generated helper contract is stale") }
    } else {
        try output.write(to: path, options: .atomic)
    }
}
