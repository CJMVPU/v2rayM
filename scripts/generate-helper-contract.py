#!/usr/bin/env python3
"""Generate language constants from the versioned helper wire contract."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def outputs(root=ROOT):
    spec = json.loads((root / 'contracts/tun-helper/contract.json').read_text())
    extensions = ', '.join(json.dumps(x) for x in spec['resourceExtensions'])
    actions = ', '.join(json.dumps(x) for x in spec['actions'])
    swift = '// Generated by scripts/generate-helper-contract.py; do not edit.\npublic enum HelperContract {\n'
    swift += f'    public static let version = {spec["protocolVersion"]}\n'
    swift += f'    public static let actions: Set<String> = [{actions}]\n'
    swift += f'    public static let resourceExtensions: Set<String> = [{extensions}]\n'
    cs = '// Generated by scripts/generate-helper-contract.py; do not edit.\nnamespace v2rayN.WebAPI.MacOS;\ninternal static class MacHelperContract\n{\n'
    cs += f'    internal const int Version = {spec["protocolVersion"]};\n'
    cs += f'    internal static readonly string[] Actions = [{actions}];\n'
    cs += f'    internal static readonly string[] ResourceExtensions = [{extensions}];\n'
    for key, value in spec['limits'].items():
        swift += f'    public static let {key} = {value}\n'
        cs += f'    internal const int {key[0].upper()+key[1:]} = {value};\n'
    return {'macos/TunHelper/Sources/TunShared/HelperContract.generated.swift': swift + '}\n',
            'v2rayN/v2rayN.WebAPI/MacOS/MacHelperContract.generated.cs': cs + '}\n'}

def main():
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    for name, text in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text: raise SystemExit(f'Generated helper contract is stale: {name}')
        else: path.write_text(text)
    print('Helper contract is current.')
if __name__ == '__main__': main()
